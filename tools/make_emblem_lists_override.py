# Generates common/coat_of_arms/template_lists/zz_jip_colored_emblem_lists.txt: copies of the vanilla colored emblem lists
# that pick an emblem by culture or faith, with the mod's emblems added. Each list is overridden by key from a file sorting
# after vanilla's colored_emblem_lists.txt, so only these lists are replaced. The emblems' textures and their CoA designer
# entries are in gfx/coat_of_arms/colored_emblems/.
#  charge                      the general charges, with vanilla's culture selections (Norse ships, the Persian simurgh):
#                              Hadad's bull, the Abgarid tiara and Bel's eagle for Arameans and Nabati, Ishtar's star and
#                              the bull for Assyrians
#  religion_icons              the faith's own emblem, by the faith's icon: the Mandaeans' (icon mandaean, the drabsha)
#  pagan_religious_icons       the pagan faiths' pool: Ishtar's star, Bel's eagle and Hadad's bull for Mesopotamianism, the
#                              bull (Baal-Hadad) for Canaanism
#  zoroastrian_religious_icons the religious title generator's pool for the Iranian and dualist faiths (holy orders, heads of
#                              faith): the drabsha for the Mandaean faith
# The faith scope can't tell the Sabian rite from the Mandaean, so Sabians may draw the drabsha too.
# Rerun after every vanilla update.
import re

VANILLA = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/common/coat_of_arms/template_lists/colored_emblem_lists.txt'
OUT = r'C:/Users/stavs/OneDrive/Documents/Paradox Interactive/Crusader Kings III/mod/jewitup/common/coat_of_arms/template_lists/zz_jip_colored_emblem_lists.txt'

# list: (vanilla line to add after, or None for the list's end, lines to add)
ADDITIONS = {
    'charge': (None, [
        '# Rising Lion: Arameans and Nabati (Hadad, Osroene, Palmyra)',
        'special_selection = {',
        '	trigger = {',
        '		scope:culture = {',
        '			OR = {',
        '				this = culture:syriac',
        '				this = culture:nabati',
        '			}',
        '		}',
        '	}',
        '	100 = "ce_jip_hadad_bull.dds"',
        '	100 = "ce_jip_abgarid_tiara.dds"',
        '	100 = "ce_jip_bel_eagle.dds"',
        '}',
        '# Rising Lion: Assyrians (Ishtar of Arbela, the bull of Hadad)',
        'special_selection = {',
        '	trigger = {',
        '		scope:culture = culture:assyrian',
        '	}',
        '	100 = "ce_jip_ishtar_star.dds"',
        '	100 = "ce_jip_hadad_bull.dds"',
        '}']),
    'religion_icons': (
        'special_selection = { trigger = { scope:faith = { has_icon = "dualism" } } 10000000 = "ce_religion_dualism.dds" }',
        ['special_selection = { trigger = { scope:faith = { has_icon = "mandaean" } } 10000000 = "ce_jip_drabsha.dds" } # Rising Lion']),
    'pagan_religious_icons': (
        'special_selection = { trigger = { scope:faith.religion = religion:paganism_religion } 100 = "ce_religion_pagan_generic.dds" }',
        ['special_selection = { trigger = { scope:faith = faith:mesopotamian_pagan } 100 = "ce_jip_ishtar_star.dds" 100 = "ce_jip_bel_eagle.dds" 100 = "ce_jip_hadad_bull.dds" } # Rising Lion',
         'special_selection = { trigger = { scope:faith = faith:semitic_pagan } 100 = "ce_jip_hadad_bull.dds" } # Rising Lion']),
    'zoroastrian_religious_icons': (
        'special_selection = { trigger = { scope:faith.religion = religion:dualism_religion } 100 = "ce_religion_dualism.dds" }',
        ['special_selection = { trigger = { scope:faith = faith:mandaean_faith } 200 = "ce_jip_drabsha.dds" } # Rising Lion']),
}

src = open(VANILLA, encoding='utf-8-sig').read().replace('\r\n', '\n')
blocks = []
for name, (anchor, lines) in ADDITIONS.items():
    m = re.search(rf'(?m)^\t{name} = \{{\n(?:.*\n)*?^\t\}}\n', src)
    assert m, name
    block = m.group(0)
    if anchor is None:
        # before the list's closing brace, after a blank line
        at = len(block) - len('\t}\n')
        block = block[:at] + '\n' + ''.join(f'\t\t{l}\n' for l in lines) + block[at:]
    else:
        am = re.search(rf'(?m)^(\t+){re.escape(anchor)}\n', block)
        assert am, (name, 'anchor')
        block = block[:am.end()] + ''.join(f'{am.group(1)}{l}\n' for l in lines) + block[am.end():]
    blocks.append(block)

header = ('# Generated by tools/make_emblem_lists_override.py from vanilla 1.20: the colored emblem lists that pick an emblem by\n'
          '# culture or faith, overridden by key with the mod\'s emblems added (marked "Rising Lion"). Rerun after every vanilla update.\n')
text = header + 'colored_emblem_texture_lists = {\n' + '\n'.join(blocks) + '}\n'
open(OUT, 'wb').write(b'\xef\xbb\xbf' + text.replace('\n', '\r\n').encode('utf-8'))
print('wrote', len(blocks), 'lists')
