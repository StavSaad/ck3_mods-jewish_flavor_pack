# Generates common/coat_of_arms/template_lists/zz_jip_colored_emblem_lists.txt: copies of the vanilla colored emblem lists
# that pick an emblem by faith, with the mod's emblems added. Each list is overridden by key from a file sorting after
# vanilla's colored_emblem_lists.txt, so only these lists are replaced. The emblems' textures and their CoA designer entries
# are in gfx/coat_of_arms/colored_emblems/.
#  religion_icons              the faith's own emblem, by the faith's icon: the Mandaeans' (icon mandaean, the drabsha)
#  zoroastrian_religious_icons the religious title generator's pool for the Iranian and dualist faiths (holy orders, heads of
#                              faith): the drabsha for the Mandaean faith
# The faith scope can't tell the Sabian rite from the Mandaean, so Sabians may draw the drabsha too.
# Rerun after every vanilla update.
import re

VANILLA = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/common/coat_of_arms/template_lists/colored_emblem_lists.txt'
OUT = r'C:/Users/stavs/OneDrive/Documents/Paradox Interactive/Crusader Kings III/mod/jewitup/common/coat_of_arms/template_lists/zz_jip_colored_emblem_lists.txt'

# list: (vanilla line to add after, lines to add)
ADDITIONS = {
    'religion_icons': (
        'special_selection = { trigger = { scope:faith = { has_icon = "dualism" } } 10000000 = "ce_religion_dualism.dds" }',
        ['special_selection = { trigger = { scope:faith = { has_icon = "mandaean" } } 10000000 = "ce_jip_drabsha.dds" } # Rising Lion']),
    'zoroastrian_religious_icons': (
        'special_selection = { trigger = { scope:faith.religion = religion:dualism_religion } 100 = "ce_religion_dualism.dds" }',
        ['special_selection = { trigger = { scope:faith = faith:mandaean_faith } 200 = "ce_jip_drabsha.dds" } # Rising Lion']),
}

src = open(VANILLA, encoding='utf-8-sig').read().replace('\r\n', '\n')
blocks = []
for name, (anchor, lines) in ADDITIONS.items():
    m = re.search(rf'(?m)^\t{name} = \{{\n(?:.*\n)*?^\t\}}\n', src)
    assert m, name
    block = m.group(0)
    am = re.search(rf'(?m)^(\t+){re.escape(anchor)}\n', block)
    assert am, (name, 'anchor')
    block = block[:am.end()] + ''.join(f'{am.group(1)}{l}\n' for l in lines) + block[am.end():]
    blocks.append(block)

header = ('# Generated by tools/make_emblem_lists_override.py from vanilla 1.20: the colored emblem lists that pick an emblem by\n'
          '# faith, overridden by key with the mod\'s emblems added (marked "Rising Lion"). Rerun after every vanilla update.\n')
text = header + 'colored_emblem_texture_lists = {\n' + '\n'.join(blocks) + '}\n'
open(OUT, 'wb').write(b'\xef\xbb\xbf' + text.replace('\n', '\r\n').encode('utf-8'))
print('wrote', len(blocks), 'lists')
