# Generates the families' copies of six Silk & Silver merchant company building lines (0.16 plan, F7): the Towers,
# the Information Network and the Accounting Office, and for the families' trade routes (F8) the Route Office, the
# Wayfinders' Hall and the Trade Mission, as estate lines for Familial heads with the DLC. The trade capacity,
# competitiveness and per-knight lines are dropped (families have no knights' trade), and a vanilla tier left with
# nothing is skipped (the Trade Mission keeps tiers 1, 2 and 4: a market on the route, then route length); vanilla's
# tiers inherit the modifiers of those below, as ours do. Costs, times and tier gates are the estate's.
# Rerun after every vanilla update. Run from the mod root.
import re

V = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/common/domiciles/buildings/00_merchant_company_buildings.txt'
OUT = 'common/domiciles/buildings/jip_familial_merchant_estate_buildings.txt'
LOC = 'localization/english/jip_familial_merchant_buildings_l_english.yml'
v = open(V, encoding='utf-8-sig').read().replace('\r\n', '\n')

# (vanilla line, our line, vanilla tiers kept, names by our tier, description)
LINES = [
    ('towers', 'jip_familial_towers', [1, 2, 3, 4, 5, 6],
     ['Watchtower', 'Twin Towers', 'Tower House', 'Fortified Towers', 'Great Tower', 'Citadel of Towers'],
     'Towers over the family\'s house, where its strongroom and its people are safe from those who would harm them.'),
    ('information_network', 'jip_familial_information_network', [1, 2, 3],
     ['Informants', 'Network of Informants', 'Web of Informants'],
     'Letters from kin and partners in every port bring the family word of what is planned, against it and for it.'),
    ('accounting_office', 'jip_familial_accounting_office', [1, 2, 3],
     ['Ledger Room', 'Accounting Office', 'Grand Accounting Office'],
     'Clerks who keep the family\'s books in order, so that nothing is lost and every building costs a little less.'),
    # The trade route lines (F8): vanilla's Wayhouse, a route length line
    ('route_office', 'jip_familial_route_office', [1, 2, 3, 4, 5, 6],
     ['Road Clerk\'s Room', 'Route Office', 'Hall of Routes', 'Office of the Roads', 'Bureau of the Roads', 'House of a Thousand Roads'],
     'Clerks who keep the family\'s maps and its factors\' reports from every town, so that its goods can be sent further along the roads.'),
    ('wayfinders_hall', 'jip_familial_wayfinders_hall', [1, 2, 3, 4, 5, 6],
     ['Guides\' Room', 'Wayfinders\' Hall', 'Hall of Guides', 'House of Wayfinders', 'Great Wayfinders\' Hall', 'College of Wayfinders'],
     'Guides who know the wells, the passes and the safe inns, for the family\'s goods and for its people on the road.'),
    ('trade_mission', 'jip_familial_trade_mission', [1, 2, 4],
     ['Trading Agent', 'Trade Mission', 'Great Trade Mission'],
     'Kin of the family who live in a distant market and buy and sell for it there, so that its routes reach one market more, and further.'),
]
# Estate tier a building of each tier needs, as vanilla's estate lines
GATE = {2: 2, 3: 2, 4: 3, 5: 4, 6: 5}
DROP = re.compile(r'trade_capacity|trade_competitiveness|_per_knight_')

def vb(k):
    m = re.search(r'^' + k + r' = \{.*?^\}', v, re.M | re.S)
    assert m, f'vanilla building {k} not found'
    return m.group(0)

out = ['\ufeff# Generated by tools/make_familial_merchant_buildings.py from vanilla\'s merchant company buildings; do not edit.',
       '# Silk & Silver lines for Familial estates (0.16 plan, F7 and F8), without trade capacity or competitiveness.', '']
loc = ['\ufeffl_english:']
for van, ours, kept, names, desc in LINES:
    assert len(kept) == len(names), van
    for i, vt in enumerate(kept, 1):
        b = vb(f'merchant_company_{van}_0{vt}')
        mods = re.search(r'\tcharacter_modifier = \{\n(.*?)\n\t\}', b, re.S).group(1).split('\n')
        mods = [m for m in mods if m.strip() and not DROP.search(m)]
        assert mods, (van, vt)
        icon = re.search(r'icon = "([^"]+)"', b).group(1)
        prev = 'estate_main_01' if i == 1 else f'{ours}_0{i - 1}'
        block = [f'{ours}_0{i} = {{',
                 '\tconstruction_time = 730',
                 '\tallowed_domicile_types = { estate }',
                 '\tslot_type = internal',
                 f'\tprevious_building = {prev}',
                 '',
                 '\tcan_construct_potential = {',
                 '\t\thas_gdp_dlc_trigger = yes',
                 '\t\tjip_can_build_mishpacha_estate_building_trigger = yes',
                 '\t}']
        if i in GATE:
            block += ['\tcan_construct = {',
                      f'\t\tdomicile ?= {{ has_domicile_building_or_higher = estate_main_0{GATE[i]} }}',
                      '\t}']
        block += ['',
                  '\tcost = {',
                  f'\t\tgold = estate_internal_building_normal_cost_tier_{i}_value',
                  '\t}',
                  '',
                  '\tcharacter_modifier = {'] + mods + ['\t}',
                  '',
                  '\tai_value = {',
                  f'\t\tvalue = {12 if i == 1 else 10}',
                  '\t}',
                  '',
                  '\tasset = {',
                  f'\t\ticon = "{icon}"',
                  '\t\ttexture = "gfx/interface/window_domiciles/estate_building_villa_byzantine.dds"',
                  '\t\tintersectionmask_texture = "gfx/interface/window_domiciles/estate_building_villa_byzantine_mask.png"',
                  '\t}',
                  '}']
        out += block
        loc.append(f' {ours}_0{i}_domicile_building: "{names[i - 1]}"')
        loc.append(f' {ours}_0{i}_domicile_building_desc: "{desc}"')
open(OUT, 'w', encoding='utf-8', newline='').write('\r\n'.join(out) + '\r\n')
open(LOC, 'w', encoding='utf-8', newline='').write('\r\n'.join(loc) + '\r\n')
print('wrote', OUT, LOC)
