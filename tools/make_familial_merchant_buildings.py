# Generates the families' copies of three Silk & Silver merchant company building lines (0.16 plan, F7): the Towers,
# the Information Network and the Accounting Office, as estate lines for Familial heads with the DLC. The trade
# capacity, competitiveness and per-knight lines are dropped (families have no knights' trade); costs, times and
# tier gates are the estate's. Rerun after every vanilla update. Run from the mod root.
import re

V = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/common/domiciles/buildings/00_merchant_company_buildings.txt'
OUT = 'common/domiciles/buildings/jip_familial_merchant_estate_buildings.txt'
LOC = 'localization/english/jip_familial_merchant_buildings_l_english.yml'
v = open(V, encoding='utf-8-sig').read().replace('\r\n', '\n')

# (vanilla line, our line, tiers, names by tier, description)
LINES = [
    ('towers', 'jip_familial_towers', 6,
     ['Watchtower', 'Twin Towers', 'Tower House', 'Fortified Towers', 'Great Tower', 'Citadel of Towers'],
     'Towers over the family\'s house, where its strongroom and its people are safe from those who would harm them.'),
    ('information_network', 'jip_familial_information_network', 3,
     ['Informants', 'Network of Informants', 'Web of Informants'],
     'Letters from kin and partners in every port bring the family word of what is planned, against it and for it.'),
    ('accounting_office', 'jip_familial_accounting_office', 3,
     ['Ledger Room', 'Accounting Office', 'Grand Accounting Office'],
     'Clerks who keep the family\'s books in order, so that nothing is lost and every building costs a little less.'),
]
# Estate tier a building of each tier needs, as vanilla's estate lines
GATE = {2: 2, 3: 2, 4: 3, 5: 4, 6: 5}
DROP = re.compile(r'trade_capacity|trade_competitiveness|_per_knight_')

def vb(k):
    m = re.search(r'^' + k + r' = \{.*?^\}', v, re.M | re.S)
    assert m, f'vanilla building {k} not found'
    return m.group(0)

out = ['\ufeff# Generated by tools/make_familial_merchant_buildings.py from vanilla\'s merchant company buildings; do not edit.',
       '# Silk & Silver lines for Familial estates (0.16 plan, F7), without trade capacity or competitiveness.', '']
loc = ['\ufeffl_english:']
for van, ours, tiers, names, desc in LINES:
    for i in range(1, tiers + 1):
        b = vb(f'merchant_company_{van}_0{i}')
        mods = re.search(r'\tcharacter_modifier = \{\n(.*?)\n\t\}', b, re.S).group(1).split('\n')
        mods = [m for m in mods if m.strip() and not DROP.search(m)]
        assert mods, (van, i)
        icon = re.search(r'icon = "([^"]+)"', b).group(1)
        prev = 'estate_main_01' if i == 1 else f'{ours}_0{i - 1}'
        block = [f'{ours}_0{i} = {{',
                 '\tconstruction_time = 730',
                 '\tallowed_domicile_types = { estate }',
                 '\tslot_type = internal',
                 f'\tprevious_building = {prev}',
                 '',
                 '\tcan_construct_potential = {',
                 '\t\thas_gdp_dlc_trigger = yes',
                 '\t\tjip_can_build_mishpacha_estate_building_trigger = yes',
                 '\t}']
        if i in GATE:
            block += ['\tcan_construct = {',
                      f'\t\tdomicile ?= {{ has_domicile_building_or_higher = estate_main_0{GATE[i]} }}',
                      '\t}']
        block += ['',
                  '\tcost = {',
                  f'\t\tgold = estate_internal_building_normal_cost_tier_{i}_value',
                  '\t}',
                  '',
                  '\tcharacter_modifier = {'] + mods + ['\t}',
                  '',
                  '\tai_value = {',
                  f'\t\tvalue = {12 if i == 1 else 10}',
                  '\t}',
                  '',
                  '\tasset = {',
                  f'\t\ticon = "{icon}"',
                  '\t\ttexture = "gfx/interface/window_domiciles/estate_building_villa_byzantine.dds"',
                  '\t\tintersectionmask_texture = "gfx/interface/window_domiciles/estate_building_villa_byzantine_mask.png"',
                  '\t}',
                  '}']
        out += block
        loc.append(f' {ours}_0{i}_domicile_building: "{names[i - 1]}"')
        loc.append(f' {ours}_0{i}_domicile_building_desc: "{desc}"')
open(OUT, 'w', encoding='utf-8', newline='').write('\r\n'.join(out) + '\r\n')
open(LOC, 'w', encoding='utf-8', newline='').write('\r\n'.join(loc) + '\r\n')
print('wrote', OUT, LOC)
