# Generates gui/hud.gui: a full copy of vanilla's HUD with one change, the council tab hidden for Familial heads too.
# Vanilla hides it only for adventurers and merchants, by a hard check no flag or rule reaches; a family has no council
# (council = no in jip_familial_government_types.txt), so the tab also checks the player's government for the council
# rule. A GUI type redefined in another file only logs "already registered", so the file is replaced by path.
# hud.gui is large and UI mods replace it too, so the change stays on that one line. Rerun after every vanilla update.
import os

VANILLA = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/gui/hud.gui'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'gui', 'hud.gui')

t = open(VANILLA, encoding='utf-8-sig').read()
PATCHES = [
    ('name = "tab_council"\n\t\t\t\t\tvisible = "[Not( Or( IsLandlessAdventurer( GetPlayer ), IsLandlessMerchant( GetPlayer ) ) )]"',
     'name = "tab_council"\n\t\t\t\t\tvisible = "[And( Not( Or( IsLandlessAdventurer( GetPlayer ), IsLandlessMerchant( GetPlayer ) ) ), '
     'GetPlayer.GetGovernment.HasRule( \'council\' ) )]" # Rising Lion: no council tab for Familial heads'),
]
for old, new in PATCHES:
    assert t.count(old) == 1, 'vanilla changed, update the patch: ' + old[:60]
    t = t.replace(old, new)
t = ('# Rising Lion: vanilla\'s hud.gui with the council tab hidden for governments without a council, the Familial (search\n'
     '# "Rising Lion"). Generated by tools/make_hud_override.py; rerun after vanilla updates.\n' + t)
open(OUT, 'wb').write(b'\xef\xbb\xbf' + t.encode('utf-8'))
print('ok')
