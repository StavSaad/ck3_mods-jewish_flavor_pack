def replace_once(old, new, start=0, end=None):
    global t
    seg = t[start:end] if end else t[start:]
    assert seg.count(old) == 1, f'vanilla changed, update the patch: {old[:60]!r}'
    i = start + seg.index(old)
    t = t[:i] + new + t[i + len(old):]


