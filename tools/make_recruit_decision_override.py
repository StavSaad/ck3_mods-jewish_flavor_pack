# Copies vanilla's Recruit for a Court Position decision (recruit_court_position_decision, from
# common/decisions/90_minor_decisions.txt) into common/decisions/jip_recruit_court_position_decision.txt with one
# change: an option for the Sabian Court Astrologer (jip_sabian_astrologer_court_position), after the Stargazer's,
# which sends to Harran for two candidates (jip_astrologer.0010), and the decision shown to Sabian Familial heads too,
# for that option (jip_is_sabian_family_trigger). Only this decision is overridden: a decision with the
# same key in a file that sorts later replaces vanilla's (the "j" file loads after "90_"). Rerun after every vanilla
# update.
import os
import re

V = r'C:\Program Files (x86)\Steam\steamapps\common\Crusader Kings III\game\common\decisions\90_minor_decisions.txt'
os.chdir(r'C:\Users\stavs\OneDrive\Documents\Paradox Interactive\Crusader Kings III\mod\jewitup')

src = open(V, encoding='utf-8-sig').read()
start = src.index('\nrecruit_court_position_decision = {') + 1
end = re.compile(r'^}', re.M).search(src, start).end() + 1
t = src[start:end]

# The option, after the Stargazer's
item_anchor = '\t\titem = { # Siege Engineer\n'
item = '''		item = { # Rising Lion: Sabian Court Astrologer
			value = jip_invite_sabian_astrologer_decision
			is_shown = {
				jip_can_employ_sabian_astrologer_trigger = yes
				exists = primary_title
				highest_held_title_tier >= tier_duchy
				is_landless_adventurer = no
			}
			is_valid = {
				can_employ_court_position_type = jip_sabian_astrologer_court_position
				NOR = {
					employs_court_position = jip_sabian_astrologer_court_position
					custom_tooltip = {
						text = jip_recruit_sabian_astrologer_cooldown_tt
						has_character_flag = jip_recruit_sabian_astrologer_cooldown
					}
				}
				exists = capital_province
			}
			current_description = jip_invite_sabian_astrologer_decision_desc
			localization = jip_invite_sabian_astrologer_decision
			icon = "gfx/interface/icons/court_position_types/jip_sabian_astrologer_court_position.dds"
			ai_chance = { value = 100 }
		}
'''

# Its effect, after the Stargazer's
effect_anchor = '\t\t\telse_if = { # Siege Engineer\n'
effect = '''			else_if = { # Rising Lion: Sabian Court Astrologer
				limit = { scope:jip_invite_sabian_astrologer_decision = yes }
				add_character_flag = {
					flag = jip_recruit_sabian_astrologer_cooldown
					years = 1
				}
				trigger_event = {
					id = jip_astrologer.0010
					days = { 7 14 }
				}
			}
'''

assert t.count(item_anchor) == 1, 'vanilla Siege Engineer option changed: update the patch'
assert t.count(effect_anchor) == 1, 'vanilla Siege Engineer effect changed: update the patch'
t = t.replace(item_anchor, item + item_anchor).replace(effect_anchor, effect + effect_anchor)
# Sabian Familial heads fail the landed check, but may send to Harran for an astrologer
shown_anchor = '\tis_shown = {\n\t\tis_landed_or_landless_administrative_or_theocratic = yes\n\t}\n'
assert t.count(shown_anchor) == 1, 'vanilla is_shown changed: update the patch'
t = t.replace(shown_anchor, '\tis_shown = {\n\t\tOR = {\n\t\t\tis_landed_or_landless_administrative_or_theocratic = yes\n'
              '\t\t\tjip_is_sabian_family_trigger = yes # Rising Lion: for the Sabian Court Astrologer\n\t\t}\n\t}\n')
t = ('# Rising Lion: vanilla\'s recruit_court_position_decision (90_minor_decisions.txt), overridden by key, with the\n'
     '# Sabian Court Astrologer option added (search "Rising Lion"). Generated by tools/make_recruit_decision_override.py;\n'
     '# rerun after vanilla updates.\n' + t)
open('common/decisions/jip_recruit_court_position_decision.txt', 'wb').write(b'\xef\xbb\xbf' + t.encode('utf-8'))
print('ok', t.count('\n'), 'lines')
