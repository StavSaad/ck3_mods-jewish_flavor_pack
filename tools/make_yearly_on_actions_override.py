# Copies vanilla common/on_action/yearly_on_actions.txt into the mod with one change: the yearly_playable_pulse cleanup
# that destroys the family titles of independent rulers holding nothing else spares Mishpacha families, so tributary
# and independent families keep their titles. An on_action's effect block can't be appended to, so the whole file is
# overridden. Rerun after every vanilla update.
import os

V = r'C:\Program Files (x86)\Steam\steamapps\common\Crusader Kings III\game\common\on_action\yearly_on_actions.txt'
os.chdir(r'C:\Users\stavs\OneDrive\Documents\Paradox Interactive\Crusader Kings III\mod\jewitup')

t = open(V, encoding='utf-8-sig').read()
old = '''				AND = {
						liege = this
						any_held_title = {
							count = all
							is_noble_family_title = yes
						}
					}'''
new = '''				AND = {
						liege = this
						any_held_title = {
							count = all
							is_noble_family_title = yes
						}
						# Rising Lion: Mishpacha families keep their family title as tributaries or independent
						# (jip_mishpacha_change_liege_effect). Generated by make_yearly_on_actions_override.py
						NOT = { government_has_flag = government_is_familial }
					}'''
assert t.count(old) == 1, 'vanilla cleanup changed: update the patch'
t = ('# Rising Lion: exact copy of vanilla yearly_on_actions.txt, except the Mishpacha exemption in yearly_playable_pulse\'s\n'
     '# family title cleanup (search "Rising Lion"). Generated by make_yearly_on_actions_override.py; rerun after vanilla updates.\n'
     + t.replace(old, new))
open('common/on_action/yearly_on_actions.txt', 'wb').write(b'\xef\xbb\xbf' + t.encode('utf-8'))
print('ok')
