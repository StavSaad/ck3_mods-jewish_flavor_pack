# Generates common/domiciles/buildings/jip_gnostic_estate_buildings.txt: the Sabian and Mandaean families' estate branches,
# copies of the Jewish ones (jip_mishpacha_estate_buildings.txt) with their own keys, triggers, parameters and icons:
#   Sabian:   Diwan (office, as the Beit Din), Haykal (temple, as the Beit Knesset); their library branch is vanilla's
#             Observatory, which raises the Mu'allim's aptitude instead (make_jewish_court_positions.py)
#   Mandaean: Scriptorium (library, as the Yeshiva), Mandi (temple, as the Beit Knesset)
# The Beit Knesset's ties and expulsion effects check its own keys, so they stay Jewish. Rerun after changing the Jewish
# branches. Run from the mod root.
import os
import re

SRC = 'common/domiciles/buildings/jip_mishpacha_estate_buildings.txt'
OUT = 'common/domiciles/buildings/jip_gnostic_estate_buildings.txt'
ICONS = 'gfx/interface/icons/domicile_building/'
# Placeholders until each branch has its own icon (make_domicile_icon.py writes ICONS + jip_domicile_building_<name>.dds)
VANILLA_ICON = {'diwan': 'domicile_building_office', 'haykal': 'domicile_building_shrine',
                'scriptorium': 'domicile_building_library', 'mandi': 'domicile_building_shrine'}

# (Jewish branch, new branch, faith)
BRANCHES = [
    ('beit_din', 'diwan', 'sabian'),
    ('beit_knesset', 'haykal', 'sabian'),
    ('yeshiva', 'scriptorium', 'mandaean'),
    ('beit_knesset', 'mandi', 'mandaean'),
]
COMMENTS = {
    'diwan': "# Diwan sub-branch of the Familial office, beside the Clerk's Office: the chancery where the Sabian secretaries of\n# Baghdad learned their trade. A copy of the Beit Din.",
    'haykal': '# Haykal sub-branch of the Familial temple, beside the Crypt: a shrine of the seven planets, as the Sabians of Harran\n# kept them. A copy of the Beit Knesset without its ties and expulsion effects, which are Jewish.',
    'scriptorium': "# Scriptorium sub-branch of the library, beside the Observatory and the Tutor's Office, where the Ginza Rabba and the\n# Mandaean books are copied. A copy of the Yeshiva.",
    'mandi': '# Mandi sub-branch of the Familial temple, beside the Crypt: the Mandaean cult hut by its pool of living water.\n# A copy of the Beit Knesset without its ties and expulsion effects, which are Jewish.',
}

src = open(SRC, encoding='utf-8-sig').read().replace('\r\n', '\n')
blocks = {m.group(1): m.group(0) for m in re.finditer(r'(?ms)^(jip_[a-z_]+_0\d) = \{.*?^\}', src)}

out = ['# Generated by make_gnostic_estate_buildings.py from jip_mishpacha_estate_buildings.txt: the Sabian and Mandaean\n'
       "# families' estate branches. Rerun after changing the Jewish branches.\n"]
for old, new, faith in BRANCHES:
    keys = sorted(k for k in blocks if re.fullmatch(f'jip_{old}_0\\d', k))
    out.append('\n' + COMMENTS[new] + '\n')
    for k in keys:
        b = blocks[k]
        b = re.sub(f'\\bjip_{old}_0', f'jip_{new}_0', b)
        b = re.sub(f'\\bjip_estate_{old}_', f'jip_estate_{new}_', b)
        b = b.replace('jip_can_build_jewish_estate_building_trigger', f'jip_can_build_{faith}_estate_building_trigger')
        b = b.replace('judaism_religion_opinion', 'dualism_religion_opinion')
        icon = f'{ICONS}jip_domicile_building_{new}.dds'
        if not os.path.exists(icon):
            icon = f'{ICONS}{VANILLA_ICON[new]}.dds'
        b = re.sub(r'icon = "[^"]+"', f'icon = "{icon}"', b)
        assert 'jewish' not in b and 'judaism' not in b and f'jip_{old}_' not in b, k
        out.append(b + '\n')

open(OUT, 'w', encoding='utf-8-sig', newline='').write(''.join(out).replace('\n', '\r\n'))
print(OUT, sum(1 for _ in re.finditer(r'(?m)^jip_\w+ = \{', ''.join(out))), 'buildings')
