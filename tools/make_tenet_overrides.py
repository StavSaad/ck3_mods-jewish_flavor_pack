# Generates common/religion/tenet_types/zz_jip_vanilla_tenet_overrides.txt: vanilla tenets overridden by key (this file
# sorts after vanilla's), each an exact copy of 1.21's with only the marked lines added:
# - Sun Worship: the Levantine faiths may pick it too (Zunists and Saura only in vanilla)
# Rerun after every vanilla update.
import os
import re

VANILLA = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/common/religion/tenet_types/00_tenet_types.txt'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   'common', 'religion', 'tenet_types', 'zz_jip_vanilla_tenet_overrides.txt')
src = open(VANILLA, encoding='utf-8-sig').read()


def vanilla_block(key):
    start = src.index('\n' + key + ' = {') + 1
    return src[start:re.compile(r'^}', re.M).search(src, start).end()]


sun = vanilla_block('tenet_sun_worship')
anchor = '\t\t\treligion = religion:zunism_religion\n'
assert sun.count(anchor) == 1, 'vanilla changed, update the patch'
sun = sun.replace(anchor, anchor + '\t\t\treligion = religion:levantine_religion # Rising Lion: Shamash, Elagabal, Yarhibol and Malakbel\n')

out = ('# Vanilla tenets overridden by key, generated by tools/make_tenet_overrides.py from 00_tenet_types.txt: exact copies with\n'
       '# only the "Rising Lion" lines added. Rerun after every vanilla update.\n'
       '# Sun Worship: the Levantine faiths may pick it too (Zunists and Saura only in vanilla)\n' + sun + '\n')
open(OUT, 'wb').write(b'\xef\xbb\xbf' + out.encode('utf-8'))
print('ok')
