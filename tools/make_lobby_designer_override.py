# Generates gui/multiplayer_types.gui: a full copy of vanilla's with a Familial button among the lobby's ruler designer
# buttons (merchant, adventurer, noble family), 0.16 plan F6. The engine designs only its own kinds of characters, so the
# button designs a landless adventurer and runs the scripted GUI jip_design_familial_house
# (common/scripted_guis/jip_lobby_scripted_guis.txt); the adventurer button runs jip_design_adventurer, which undoes it.
# After the lobby jip_familial_custom_family_start_on_action settles the designed adventurer as a family.
# A GUI type redefined in another file only logs "already registered", so the file is replaced by path.
# Rerun after every vanilla update.
import os

VANILLA = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/gui/multiplayer_types.gui'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'gui', 'multiplayer_types.gui')

t = open(VANILLA, encoding='utf-8-sig').read()
ADV = ('\t\t\t\tbutton_round_lobby_ruler_designer = {\n'
       '\t\t\t\t\tvisible = "[CanMakeLandlessCharacter]"\n'
       '\t\t\t\t\tenabled = "[LobbyView.HasSelectedPlayable]"\n'
       '\t\t\t\t\tonclick = "[TryStartRulerDesigning( Character.Self, \'landless_adventurer\' )]"\n'
       '\t\t\t\t\ttooltip = "RULER_DESIGNER_OPEN_LANDLESS_ADVENTURER"\n'
       '\n'
       '\t\t\t\t\tblockoverride "designer_icon" {\n'
       '\t\t\t\t\t\ttexture = "gfx/interface/icons/flat_icons/map_modes/landless_rulers.dds"\n'
       '\t\t\t\t\t}\n'
       '\t\t\t\t}\n')
assert t.count(ADV) == 1, 'vanilla changed, update the patch'
NEW = (ADV.replace('\t\t\t\t\tonclick = "[TryStartRulerDesigning',
                   '\t\t\t\t\tonclick = "[GetScriptedGui( \'jip_design_adventurer\' ).Execute( GuiScope.SetRoot( Character.MakeScope ).End )]" # Rising Lion\n'
                   '\t\t\t\t\tonclick = "[TryStartRulerDesigning', 1)
       + '\n\t\t\t\t# Rising Lion: a Familial house, designed as an adventurer and settled after the lobby\n'
       '\t\t\t\tbutton_round_lobby_ruler_designer = {\n'
       '\t\t\t\t\tvisible = "[CanMakeLandlessCharacter]"\n'
       '\t\t\t\t\tenabled = "[LobbyView.HasSelectedPlayable]"\n'
       '\t\t\t\t\tonclick = "[GetScriptedGui( \'jip_design_familial_house\' ).Execute( GuiScope.SetRoot( Character.MakeScope ).End )]"\n'
       '\t\t\t\t\tonclick = "[TryStartRulerDesigning( Character.Self, \'landless_adventurer\' )]"\n'
       '\t\t\t\t\ttooltip = "JIP_RULER_DESIGNER_OPEN_FAMILIAL"\n'
       '\n'
       '\t\t\t\t\tblockoverride "designer_icon" {\n'
       '\t\t\t\t\t\ttexture = "gfx/interface/icons/flat_icons/jip_familial_designer.dds"\n'
       '\t\t\t\t\t}\n'
       '\t\t\t\t}\n')
t = t.replace(ADV, NEW)
t = ('# Rising Lion: vanilla\'s multiplayer_types.gui with a Familial button among the lobby\'s ruler designer buttons\n'
     '# (search "Rising Lion"). Generated by tools/make_lobby_designer_override.py; rerun after vanilla updates.\n' + t)
open(OUT, 'wb').write(b'\xef\xbb\xbf' + t.encode('utf-8'))
print('ok')
