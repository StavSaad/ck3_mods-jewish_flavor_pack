# Generates gui/window_county_view.gui: a full copy of vanilla's county view with one change, the "move domicile" button
# (and the spacer beside it) shown to Familial heads as well as landless adventurers, so a family can move its estate from
# the province view. A GUI type redefined in another file only logs "already registered", so the file is replaced by path.
# Rerun after every vanilla update.
import os

VANILLA = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/gui/window_county_view.gui'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'gui', 'window_county_view.gui')
GOV = "GetPlayer.GetGovernment.IsType( 'familial_government' )"

t = open(VANILLA, encoding='utf-8-sig').read()
PATCHES = [
    ('visible = "[IsLandlessAdventurer( GetPlayer )]"\n\t\t\t\t\t\t\t\twidgetid = "move_domcicle_button"',
     f'visible = "[Or( IsLandlessAdventurer( GetPlayer ), {GOV} )]" # Rising Lion: Familial heads move their estate here\n'
     '\t\t\t\t\t\t\t\twidgetid = "move_domcicle_button"'),
    ('visible = "[Or( IsLandlessAdventurer( GetPlayer ), County.IsFullyOccupied )]"',
     f'visible = "[Or( Or( IsLandlessAdventurer( GetPlayer ), {GOV} ), County.IsFullyOccupied )]" # Rising Lion: as the button'),
]
for old, new in PATCHES:
    assert t.count(old) == 1, 'vanilla changed, update the patch: ' + old[:60]
    t = t.replace(old, new)
t = ('# Rising Lion: vanilla\'s window_county_view.gui with the move domicile button shown to Familial heads (search "Rising\n'
     '# Lion"). Generated by tools/make_county_view_override.py; rerun after vanilla updates.\n' + t)
open(OUT, 'wb').write(b'\xef\xbb\xbf' + t.encode('utf-8'))
print('ok')
