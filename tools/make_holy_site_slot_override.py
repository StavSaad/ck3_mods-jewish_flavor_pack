# Generates common/scripted_effects/zz_jip_holy_site_slot_effects.txt: vanilla's add_holy_site_fallback_special_district_slot_effect
# (common/scripted_effects/00_religion_effects.txt), overridden by key (this file sorts after vanilla's), with two branches
# first: a holy site of Mesopotamianism with no special district slot gets the slot of our ziggurat
# (jip_holy_site_ziggurat_01_district), one of Arameanism our classical temple's (jip_holy_site_classical_temple_01_district),
# instead of the pagan grand temple. Called by vanilla at game start for every holy site (on_action/game_start.txt) and when
# a holy site is created (religion_on_actions.txt). Rerun after every vanilla update.
import os
import re

VANILLA = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/common/scripted_effects/00_religion_effects.txt'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   'common', 'scripted_effects', 'zz_jip_holy_site_slot_effects.txt')
KEY = 'add_holy_site_fallback_special_district_slot_effect'

src = open(VANILLA, encoding='utf-8-sig').read()
start = src.index('\n' + KEY + ' = {') + 1
end = re.compile(r'^}', re.M).search(src, start).end()
t = src[start:end]

first = '\t\tif = {\n\t\t\tlimit = { $FAITH$ = { religion = religion:islam_religion } }\n'
assert t.count(first) == 1, 'vanilla changed, update the patch'
ours = ('\t\t# Rising Lion: the old faith\'s holy sites take a ziggurat\n'
        '\t\tif = {\n\t\t\tlimit = { $FAITH$ = { this = faith:mesopotamian_pagan } }\n'
        '\t\t\tadd_special_district_slot = jip_holy_site_ziggurat_01_district\n\t\t}\n'
        '\t\t# Rising Lion: Arameanism\'s take a classical temple\n'
        '\t\telse_if = {\n\t\t\tlimit = { $FAITH$ = { this = faith:aramean_pagan } }\n'
        '\t\t\tadd_special_district_slot = jip_holy_site_classical_temple_01_district\n\t\t}\n'
        '\t\telse_if = {\n\t\t\tlimit = { $FAITH$ = { religion = religion:islam_religion } }\n')
t = t.replace(first, ours)
head = ('# Rising Lion: vanilla\'s ' + KEY + ' (00_religion_effects.txt), overridden by key: the\n'
        '# Mesopotamian and Aramean pagan holy sites take our ziggurat and classical temple districts (search "Rising Lion").\n'
        '# Generated by tools/make_holy_site_slot_override.py; rerun after every vanilla update.\n\n')
open(OUT, 'wb').write(b'\xef\xbb\xbf' + (head + t + '\n').encode('utf-8'))
print('ok')
