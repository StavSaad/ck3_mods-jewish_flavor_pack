# Generates gui/window_situation_list.gui: a full copy of vanilla's situations and stories window, replacing it by path,
# with the Sabian story's houses of the gods (0.15 plan, section 10) added to the story entry (vbox_story_cycle_entry)
# after its custom string: in Acts IV and V (the story variable jip_sabian_show_sites), a column for each of the six gods
# (in Act IV only Sin's at Harran: the others wait for jip_sabian_show_all_sites, set in Act V)
# with the icon of its temple's great project (faded until the temple stands, a check once its statue is home; the
# status as a tooltip, JipSabianSite<God> custom loc) and the coat of arms of its county, which opens the title view.
# Also writes the scripted GUIs the columns check (common/scripted_guis/jip_sabian_story_guis.txt), on the story owner.
# Not overridden by type: a type registered twice only logs "already registered", with no word on which one is kept.
# Rerun after every vanilla update.
import re

VANILLA = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/gui/window_situation_list.gui'
MOD = r'C:/Users/stavs/OneDrive/Documents/Paradox Interactive/Crusader Kings III/mod/jewitup/'

# god, custom loc suffix, temple barony, county (its coat of arms), temple building, great project icon
GODS = [
    ('sin', 'Sin', 'b_harran', 'c_harran', 'jip_temple_of_sin_01', 'jip_temple_of_sin'),
    ('ishtar', 'Ishtar', 'b_irbil', 'c_irbil', 'jip_temple_of_ishtar_01', 'jip_temple_of_ishtar'),
    ('ashur', 'Ashur', 'b_ain_al-qayyara', 'c_mosul', 'jip_temple_of_ashur_01', 'jip_temple_of_ashur'),
    ('bel', 'Bel', 'b_tadmur', 'c_palmyra', 'jip_temple_of_bel_01', 'jip_temple_of_bel'),
    ('shamash', 'Shamash', 'b_al-hadr', 'c_mosul', 'jip_temple_of_shamash_01', 'jip_temple_of_shamash'),
    ('marduk', 'Marduk', 'b_al-hila', 'c_kufa', 'jip_temple_of_marduk_01', 'jip_temple_of_marduk'),
]


def shown(gui):
    return f"GetScriptedGui('{gui}').IsShown( GuiScope.SetRoot( Story.GetOwner.MakeScope ).End )"


def column(god, suffix, county, icon):
    tex = f'gfx/interface/icons/great_projects/{icon}.dds'
    temple, home, held = (f'jip_sabian_site_{k}_{god}' for k in ('temple', 'home', 'held'))
    # A fixed-size column with its parts at fixed positions, centred on its middle (x 36): a vbox ignores parentanchor,
    # so its rows sat unevenly and the CoA covered the name
    only_act_5 = '' if god == 'sin' else "\n\t\t\t\t\t\tvisible = \"[Story.MakeScope.HasFlag('jip_sabian_show_all_sites')]\""
    return f'''
					widget = {{{only_act_5}
						size = {{ 72 144 }}

						widget = {{
							position = {{ 4 0 }}
							size = {{ 64 64 }}
							tooltip = "[Story.GetOwner.Custom('JipSabianSite{suffix}')]"

							icon = {{
								visible = "[{shown(temple)}]"
								size = {{ 64 64 }}
								texture = "{tex}"
							}}
							icon = {{
								visible = "[Not( {shown(temple)} )]"
								size = {{ 64 64 }}
								texture = "{tex}"
								alpha = 0.3
							}}
							icon = {{
								visible = "[{shown(home)}]"
								parentanchor = bottom|right
								size = {{ 24 24 }}
								texture = "gfx/interface/icons/symbols/icon_check.dds"
							}}
						}}

						text_single = {{
							position = {{ 0 66 }}
							size = {{ 72 20 }}
							autoresize = no
							text = "jip_sabian_god_{god}"
							using = Font_Size_Small
							align = center|nobaseline
						}}

						widget = {{
							position = {{ 10 90 }}
							size = {{ 52 52 }}

							widget = {{
								visible = "[{shown(held)}]"
								size = {{ 52 52 }}
								coa_title_small = {{
									datacontext = "[GetTitleByKey('{county}')]"
								}}
							}}
							widget = {{
								visible = "[Not( {shown(held)} )]"
								size = {{ 52 52 }}
								alpha = 0.45
								coa_title_small = {{
									datacontext = "[GetTitleByKey('{county}')]"
								}}
							}}
						}}
					}}'''


BLOCK = '''
		# Rising Lion: the houses of the old gods in the Sabian story's Acts IV and V (tools/make_story_window_override.py)
		vbox = {
			visible = "[Story.MakeScope.HasFlag('jip_sabian_show_sites')]"
			layoutpolicy_horizontal = expanding
			margin = { 10 5 }

			background = { using = Background_Story }

			text_single = {
				layoutpolicy_horizontal = expanding
				text = "JIP_SABIAN_GODS_HOUSES"
				using = Font_Size_Medium
				margin_top = 2
				margin_left = 20
			}

			hbox = {
				margin = { 0 6 }
				spacing = 4
''' + ''.join(column(g, s, c, i).replace('\n\t', '\n') for g, s, _, c, _, i in GODS) + '''
			}
		}
'''

src = open(VANILLA, encoding='utf-8-sig').read().replace('\r\n', '\n')
anchor = re.search(r'\n\t\t# Custom String Key\n\t\tvbox = \{\n\t\t\tvisible = "\[Story\.HasCustomString\]"\n(?:.*\n)*?\t\t\}\n', src)
assert anchor, 'custom string block'
out = src[:anchor.end()] + BLOCK + src[anchor.end():]
header = ('# Generated by tools/make_story_window_override.py from vanilla 1.20: a full copy of vanilla\'s file with the Sabian\n'
          '# story\'s houses of the gods added (marked "Rising Lion"). Rerun after every vanilla update.\n')
open(MOD + 'gui/window_situation_list.gui', 'wb').write(b'\xef\xbb\xbf' + (header + out).replace('\n', '\r\n').encode('utf-8'))

guis = ['# Generated by tools/make_story_window_override.py: the Sabian story window\'s houses of the gods, checked on the story',
        '# owner (gui/window_situation_list.gui)']
for god, _, barony, _, building, _ in GODS:
    guis += ['', f'# {god}: the temple stands', f'jip_sabian_site_temple_{god} = {{', '\tscope = character', '\tis_shown = {',
             f'\t\ttitle:{barony}.title_province = {{ has_building = {building} }}', '\t}', '}',
             '', f'# {god}: the statue is home', f'jip_sabian_site_home_{god} = {{', '\tscope = character', '\tis_shown = {',
             f'\t\tis_target_in_global_variable_list = {{ name = jip_old_gods_home target = flag:{god} }}', '\t}', '}',
             '', f'# {god}: the temple\'s barony is in the owner\'s realm', f'jip_sabian_site_held_{god} = {{', '\tscope = character',
             '\tis_shown = {', f'\t\ttitle:{barony}.holder ?= {{ target_is_same_character_or_above = root }}', '\t}', '}']
open(MOD + 'common/scripted_guis/jip_sabian_story_guis.txt', 'wb').write(
    b'\xef\xbb\xbf' + ('\n'.join(guis) + '\n').replace('\n', '\r\n').encode('utf-8'))
print('wrote gui/window_situation_list.gui and common/scripted_guis/jip_sabian_story_guis.txt')
