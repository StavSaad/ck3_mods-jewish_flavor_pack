# Generates common/religion/rite_types/02_mainline_rite_types.txt: vanilla's file of the same name (one scripted rite per
# faith that would otherwise only get an engine-generated one) without the Jewish faiths' rites, which
# jip_jewish_rite_types.txt defines with the mod's changes. Same path as vanilla's, so it replaces it instead of defining
# every rite twice. Rerun after every vanilla update; if vanilla renames the file again, delete the old copy.
import os
import re

VANILLA = r'C:/Program Files (x86)/Steam/steamapps/common/Crusader Kings III/game/common/religion/rite_types/02_mainline_rite_types.txt'
MOD = r'C:/Users/stavs/OneDrive/Documents/Paradox Interactive/Crusader Kings III/mod/jewitup/'
OUT = MOD + 'common/religion/rite_types/02_mainline_rite_types.txt'
OURS = MOD + 'common/religion/rite_types/jip_jewish_rite_types.txt'

ours = set(re.findall(r'(?m)^(\w+) = \{', open(OURS, encoding='utf-8-sig').read()))
text = open(VANILLA, encoding='utf-8-sig').read().replace('\r\n', '\n')
removed = []


def drop(m):
    if m.group(1) in ours:
        removed.append(m.group(1))
        return ''
    return m.group(0)


text = re.sub(r'(?ms)^(\w+) = \{\n.*?^\}\n\n?', drop, text)
assert set(removed) == {'karaism', 'haymanot', 'malabarism', 'samaritan', 'kabarism'}, removed
header = ("# Generated by make_mainline_rite_types_override.py from vanilla's file of the same name, without the Jewish faiths'\n"
          '# rites (' + ', '.join(removed) + '), which jip_jewish_rite_types.txt defines. Rerun after every vanilla update.\n\n')
open(OUT, 'wb').write(b'\xef\xbb\xbf' + (header + text).replace('\n', '\r\n').encode('utf-8'))
print('removed', removed)
