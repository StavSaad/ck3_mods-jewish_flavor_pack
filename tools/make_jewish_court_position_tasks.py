def override(file, key, positions, shown, why):
    b = vanilla_block(file, key)
    add = ' '.join(f'{p}_court_position' for p in positions)
    b, n = re.subn(r'(court_position_types = \{)([^}]*)\}', lambda m: f'{m.group(1)} {m.group(2).strip()} {add} }}', b, count=1)
    assert n == 1, key
    if shown:
        lines = ''.join(f'\t\t{line}\n' for line in shown)
        m = re.search(r'\n\tis_shown = \{([^{}]*)\}', b)
        if m:
            inner = m.group(1).strip()
            body = (f'\t\t{inner}\n' if inner else '') + lines
            b = b[:m.start()] + f'\n\tis_shown = {{\n{body}\t}}' + b[m.end():]
        else:
            # No is_shown in vanilla: add one after court_position_types
            b = re.sub(r'(\tcourt_position_types = \{[^}]*\}\n)', lambda mm: mm.group(1) + f'\n\tis_shown = {{\n{lines}\t}}\n', b, count=1)
        assert lines in b, key
    return f'# {key} ({file}): + {why}\n{b}\n'


