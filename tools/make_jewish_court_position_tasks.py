def vanilla_block(file, key):
    t = open(V + file, encoding='utf-8-sig').read().replace('\r\n', '\n')
    m = re.search(r'^' + key + r' = \{', t, re.M)
    d, j = 1, m.end()
    while d:
        if t[j] == '{':
            d += 1
        elif t[j] == '}':
            d -= 1
        j += 1
    return t[m.start():j]


