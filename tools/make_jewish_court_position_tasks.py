def cost(kind, mult=None):
    if kind == 'prestige':
        return PRESTIGE_COST
    return GOLD_COST.replace('\t\t\t\t\tMULT\n', f'\t\t\t\t\tmultiply = {mult}\n' if mult else '')


def mods(name, d, n=1):
    t = '\t' * n
    return f'{t}{name} = {{\n' + ''.join(f'{t}\t{k} = {v}\n' for k, v in d.items()) + f'{t}}}\n'


def scaling(levels):
    return '\tscaling_employer_modifiers = {\n' + ''.join(mods(lv, s, 2) for lv, s in zip(LEVELS, levels)) + '\t}\n'


def ind(text, n):
    return ''.join(('\t' * n + line if line else '') + '\n' for line in text.strip('\n').split('\n'))


def task(key, positions, comment, cost_block, employee, levels, shown='', valid='', on_start='', on_end='', on_yearly='', ai='\tvalue = 25'):
    o = f'# {comment}\n{key} = {{\n'
    o += '\tcourt_position_types = { ' + ' '.join(f'{p}_court_position' for p in positions) + ' }\n\n'
    o += cost_block + '\n'
    o += mods('employee_modifier', employee) + '\n' if employee else ''
    o += scaling(levels) + '\n'
    o += '\tis_shown = {\n' + (ind(shown, 2) if shown else '') + '\t}\n'
    o += '\tis_valid_showing_failures_only = {\n' + (ind(valid, 2) if valid else '') + '\t}\n\n'
    o += '\ton_start = {\n' + (ind(on_start, 2) if on_start else '') + '\t}\n'
    o += '\ton_end = {\n' + (ind(on_end, 2) if on_end else '') + '\t}\n'
    if on_yearly:
        o += '\ton_yearly = {\n' + ind(on_yearly, 2) + '\t}\n'
    o += '\n\tai_will_do = {\n' + ind(ai, 2) + '\t}\n}\n'
    return o


def chance(position, base, per_level):
    # A yearly roll that grows with the holder's aptitude level (0-4)
    return f'''random = {{
	chance = {{
		value = "aptitude({position}_court_position)"
		multiply = {per_level}
		add = {base}
	}}
'''


