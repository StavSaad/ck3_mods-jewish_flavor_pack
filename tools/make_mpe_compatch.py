def sub_words(text, mapping):
    if not mapping:
        return text
    pat = re.compile(r"(?<![A-Za-z0-9_\-'])(%s)(?![A-Za-z0-9_\-'])" % '|'.join(map(re.escape, mapping)))
    return pat.sub(lambda m: mapping[m.group(1)], text)


def copy_with(src, mapping, extra=None):
    text = read(JIP + '/' + src)
    text = sub_words(text, mapping)
    if extra:
        text = extra(text)
    return HEADER % src + text


