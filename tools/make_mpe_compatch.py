def barony_at(tree, prov):
    for k, t in tree.items():
        if k.startswith('b_') and get_prop(t, 'province') == prov:
            return k
    return None


def descends(tree, t, ancestor):
    while t:
        if t == ancestor:
            return True
        t = tree[t]['parent'] if t in tree else None
    return False


