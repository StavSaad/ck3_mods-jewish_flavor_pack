def read(path):
    with open(path, encoding='utf-8-sig', errors='replace') as f:
        return f.read()


# ---------------------------------------------------------------- the three title trees

def title_files(root):
    return {os.path.basename(p): p for p in glob.glob(root + '/common/landed_titles/*.txt')}


def load_tree(paths):
    """title -> {'props': [items], 'parent': key, 'kids': [keys]}, over the files in order the way the game reads
    them: the properties and parent of the last definition, children from every definition"""
    tree, order = {}, []
    for path in paths:
        def walk(items, parent):
            for k, op, v in items:
                if k and TITLE.match(k) and isinstance(v, P.Block):
                    t = tree.get(k)
                    if t is None:
                        t = tree[k] = {'props': [], 'parent': parent, 'kids': []}
                        order.append(k)
                    else:
                        old = t['parent']
                        if old and old != parent and k in tree[old]['kids']:
                            tree[old]['kids'].remove(k)
                        t['parent'] = parent
                        t['props'] = []
                    if parent and k not in tree[parent]['kids']:
                        tree[parent]['kids'].append(k)
                    for item in v:
                        if not (item[0] and TITLE.match(item[0]) and isinstance(item[2], P.Block)):
                            set_prop(t['props'], item)
                    walk(v, k)
        walk(P.parse(read(path)), None)
    return tree, order


def set_prop(props, item):
    k = item[0]
    if k is not None:
        for i, old in enumerate(props):
            if old[0] == k:
                props[i] = item
                return
    props.append(item)


def get_prop(t, key):
    for k, op, v in t['props']:
        if k == key:
            return v
    return None


