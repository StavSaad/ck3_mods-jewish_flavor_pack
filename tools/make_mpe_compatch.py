"""Builds the Rising Lion compatch for More Provinces Expanded (workshop 2960153137) into ../../jipmpe.

Load order: More Provinces Expanded, Rising Lion, the compatch. Every file the compatch writes replaces Rising Lion's
file of the same path, so rerun this after changing any of the source files below, and after an MPE update.

What it does:
- common/landed_titles/jip_landed_titles.txt: Rising Lion's titles nested where MPE puts them. A title defined twice
  takes its parent and all its properties from the later definition (a property left out, like color, is lost), but
  keeps its children, so Rising Lion's file, nested on vanilla's map, pulls MPE's baronies and duchies back into
  vanilla's counties and kingdoms. Here every title written restates MPE's properties with what Rising Lion changed
  from vanilla over them, under MPE's parent; MPE's new counties and duchies above Rising Lion's named baronies take
  the names of the first such barony
- the regions (map_data/geographical_regions/jip_geographical_regions.txt), the holy sites, the special building
  slots, and the files that name the temples' counties or baronies, with MPE's titles
- the 867 setup and the rite-name triggers: every county MPE carved out of a vanilla county is set or checked like it

Run: python tools/make_mpe_compatch.py [--check]   (--check reports without writing)
"""
