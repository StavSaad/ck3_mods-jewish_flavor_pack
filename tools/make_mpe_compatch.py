def merge_cultural_names(m_block, o_block):
    entries = {}
    for k, op, v in (m_block or []):
        entries[k] = (k, op, v)
    for k, op, v in o_block:
        entries[k] = (k, op, v)
    return P.Block(entries.values())


def own_props(t):
    """Rising Lion's properties on a vanilla title, minus those it only repeats from vanilla"""
    out = []
    o, v, m = O[t], V.get(t), M.get(t)
    for item in o['props']:
        k, op, val = item
        if k is None:
            continue
        if v is not None:
            vv = get_prop(v, k)
            if vv is not None and P.same(vv, val):
                continue
        if k == 'cultural_names' and isinstance(val, P.Block):
            # only our entries; MPE's are merged in when the file is written
            vv = get_prop(v, k) if v else None
            vd = {x[0]: x[2] for x in vv} if isinstance(vv, P.Block) else {}
            ours = P.Block(x for x in val if not (x[0] in vd and vd[x[0]] == x[2]))
            if ours:
                out.append((k, op, ours))
            continue
        # a capital outside the title's de jure land (titular titles, like Beth Nahrain, have none) is MPE's
        if k == 'capital' and m is not None and m['kids'] and not descends(M, val, t):
            warnings.append('%s: capital %s is not in its de jure land on MPE\'s map; kept MPE\'s' % (t, val))
            continue
        out.append(item)
    return out


def build_landed_titles():
    props = {}        # title -> props to write
    parent = {}       # title -> parent in the output
    for t in O_ORDER:
        if t in V and t not in M:
            if t in NAMES_REMAP:
                continue
            warnings.append('%s: not on MPE\'s map; its definition is dropped' % t)
            continue
        if t in V:
            target = NAMES_REMAP.get(t, t)
            p = own_props(t)
            if target != t:   # the names follow the province
                p = [x for x in p if x[0] == 'cultural_names']
            props[target] = props.get(target, []) + p
            parent[target] = M[target]['parent']
        else:   # Rising Lion's own title: as it is, under its own parent
            props[t] = [x for x in O[t]['props'] if x[0] is not None]
            parent[t] = O[t]['parent']
            cap = get_prop(O[t], 'capital')
            if cap and cap not in M:
                warnings.append('%s: capital %s is not on MPE\'s map' % (t, cap))
    # A county named after one of its baronies (Acre is "Tyre" for Canaanites: cultural name b_tyre) gives that name
    # to the county that holds the barony on MPE's map
    for t in list(props):
        if not t.startswith('c_'):
            continue
        for i, (k, op, v) in enumerate(props[t]):
            if k != 'cultural_names' or not isinstance(v, P.Block):
                continue
            keep = P.Block()
            for nk, nop, nv in v:
                home = county_of(M, nv) if isinstance(nv, str) and nv.startswith('b_') else None
                if home and home != t:
                    dest = props.setdefault(home, [])
                    parent.setdefault(home, M[home]['parent'])
                    cn = next((j for j, x in enumerate(dest) if x[0] == 'cultural_names'), None)
                    if cn is None:
                        dest.append(('cultural_names', '=', P.Block([(nk, nop, nv)])))
                    else:
                        set_prop(dest[cn][2], (nk, nop, nv))
                else:
                    keep.append((nk, nop, nv))
            props[t][i] = (k, op, keep)
        props[t] = [x for x in props[t] if not (x[0] == 'cultural_names' and not x[2])]
    # nothing of ours on a title MPE already nests the same way: leave it out
    for t in list(parent):
        if not props[t] and t in M and parent[t] == M[t]['parent']:
            del parent[t]
    # wrappers: every ancestor on MPE's map of a title written
    for t in list(parent):
        p = parent[t]
        while p and p not in parent:
            parent[p] = M[p]['parent'] if p in M else O[p]['parent']
            props.setdefault(p, [])
            p = parent[p]
    # MPE's new counties and duchies above a named barony take the first named barony's names
    named = {t for t in props if any(k == 'cultural_names' for k, _, _ in props[t])}
    for t in sorted(props):
        if t in V or t not in M or t[0] not in 'cd' or any(k == 'cultural_names' for k, _, _ in props[t]):
            continue
        if t.startswith('c_'):
            src = next((b for b in M[t]['kids'] if b in named), None)
        else:
            cap = get_prop(M[t], 'capital')
            src = cap if cap in named else None
            if src is None and cap in M:
                src = next((b for b in M[cap]['kids'] if b in named), None)
        if src:
            cn = next(v for k, _, v in props[src] if k == 'cultural_names')
            props[t].append(('cultural_names', '=', P.Block(cn)))
            named.add(t)
    # our names over MPE's: a title's cultural_names replaces the whole block, so MPE's entries are restated
    for t in props:
        if t not in M:
            continue
        for i, (k, op, v) in enumerate(props[t]):
            if k == 'cultural_names' and isinstance(v, P.Block):
                mv = get_prop(M[t], k)
                props[t][i] = (k, op, merge_cultural_names(mv if isinstance(mv, P.Block) else None, v))
    # every county written lists all its baronies, and every barony its province, as MPE's own definitions do
    for c in [t for t in parent if t.startswith('c_') and t in M]:
        for b in M[c]['kids']:
            if b not in parent:
                parent[b] = c
                props[b] = []
    # A redefinition replaces the title's properties (only its children stay): every title written restates all of
    # MPE's (color, capital, province, can_create...) with ours over them
    for t in parent:
        if t not in M:
            continue
        full = [x for x in M[t]['props'] if x[0] is not None]
        for item in props[t]:
            set_prop(full, item)
        props[t] = full
    children = {}
    for t, p in parent.items():
        children.setdefault(p, []).append(t)

    def order_key(t):
        p = parent[t]
        sib = (M[p]['kids'] if p in M else O[p]['kids']) if p else None
        if sib and t in sib:
            return (0, sib.index(t))
        return (1, O_ORDER.index(t) if t in O_ORDER else 10 ** 6)

    def emit(t):
        block = P.Block(props[t])
        for c in sorted(children.get(t, []), key=order_key):
            block.append((c, '=', emit(c)))
        return block

    roots = sorted(children.get(None, []), key=lambda t: O_ORDER.index(t) if t in O_ORDER else 10 ** 6)
    items = [x for x in O_ITEMS if x[0] and x[0].startswith('@')]
    for t in roots:
        items.append((t, '=', emit(t)))
    return HEADER % 'common/landed_titles/jip_landed_titles.txt' + '\n' + P.write(items)


