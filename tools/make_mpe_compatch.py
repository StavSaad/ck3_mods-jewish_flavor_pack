def province_history(text):
    for old, new in PROVINCE_REMAP.items():
        text = re.sub(r'(?m)^%s = \{' % old, '%s = {' % new, text)
        text = text.replace('# %s - ZUGHAR (Negev capital' % old, '# %s - MASADA (MPE\'s b_masada' % new)
    return text


def kemet_abwab(text):
    """Kemet's effect moves Makuria's duchies by name; MPE's Abwab, carved from Makuria, moves with it"""
    for king in ('k_blemmyia', 'k_upper_egypt'):
        line = 'title:d_makuria = { set_de_jure_liege_title = title:%s }' % king
        if line in text:
            text = text.replace(line, line + '\n\t\ttitle:d_abwab = { set_de_jure_liege_title = title:%s }' % king, 1)
        else:
            warnings.append('Kemet: no line "%s" to add Abwab to' % line)
    return text


def find_block_end(text, start):
    """index just past the } closing the { at or after start"""
    i = text.index('{', start)
    depth = 0
    while i < len(text):
        ch = text[i]
        if ch == '#':
            i = text.index('\n', i) if '\n' in text[i:] else len(text)
            continue
        if ch == '"':
            i = text.index('"', i + 1)
        elif ch == '{':
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError('unbalanced block at %d' % start)


def split_county_blocks(text):
    """Every `title:c_X = { ... }` that a county MPE split runs again for each county carved from it"""
    out, pos = [], 0
    for m in re.finditer(r'(?m)^([ \t]*)title:(c_[A-Za-z0-9_\-]+) = \{', text):
        if m.start() < pos:
            continue
        c = m.group(2)
        extra = [x for x in SPLIT.get(c, []) if x != c]
        if not extra:
            continue
        end = find_block_end(text, m.start())
        block = text[m.start():end]
        out.append(text[pos:end])
        for x in extra:
            out.append('\n' + block.replace('title:%s = {' % c, 'title:%s = {	# MPE, carved from %s' % (x, c), 1))
        pos = end
    out.append(text[pos:])
    return ''.join(out)


def split_county_triggers(text):
    """A founder's capital checked against a county MPE split also counts the counties carved from it"""
    def rep(m):
        c = m.group(2)
        extra = [x for x in SPLIT.get(c, []) if x != c]
        if not extra:
            return m.group(0)
        alts = ' '.join('jip_rite_founder_capital_trigger = { COUNTY = %s }' % x for x in [c] + extra)
        return '%sOR = { %s }' % (m.group(1), alts)
    return re.sub(r'(?m)^([ \t]*)jip_rite_founder_capital_trigger = \{ COUNTY = (c_[A-Za-z0-9_\-]+) \}', rep, text)


def merge_dynamic_coas(text):
    """MPE's crusader arms for Edessa and Syria after Rising Lion's Aramean ones (the first item that applies wins)"""
    m_items = {}
    for p in glob.glob(MPE + '/common/coat_of_arms/dynamic_definitions/*.txt'):
        for k, op, v in P.parse(read(p)):
            if isinstance(v, P.Block):
                m_items[k] = [x for x in v if x[0] == 'item']
    items = P.parse(text)
    for i, (k, op, v) in enumerate(items):
        if k in m_items and isinstance(v, P.Block):
            items[i] = (k, op, P.Block(list(v) + m_items[k]))
    return P.write(items)


