def build_regions():
    src = 'map_data/geographical_regions/jip_geographical_regions.txt'
    items = P.parse(read(JIP + '/' + src))
    out = []
    for k, op, v in items:
        if k in REGION_BLOCKS:
            block = P.Block()
            for kind in ('regions', 'kingdoms', 'duchies', 'counties'):
                keys = REGION_BLOCKS[k].get(kind)
                if keys:
                    for x in keys:
                        if kind != 'regions' and x not in M:
                            warnings.append('region %s: %s is not on MPE\'s map' % (k, x))
                    block.append((kind, '=', P.Block((None, None, x) for x in keys)))
            v = block
        out.append((k, op, v))
    # every province once per region
    return HEADER % src + '\n' + P.write(out)


