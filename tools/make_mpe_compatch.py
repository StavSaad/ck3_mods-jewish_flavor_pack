def build_holy_sites():
    src = 'common/religion/holy_site_types/jip_holy_sites.txt'
    items = P.parse(read(JIP + '/' + src))
    for k, op, v in items:
        if not isinstance(v, P.Block):
            continue
        b = next((x for kk, _, x in v if kk == 'barony'), None)
        c = next((x for kk, _, x in v if kk == 'county'), None)
        if b:
            b2 = BARONY_REMAP.get(b, b)
            if b2 == 'b_masada':
                b2 = b
            c2 = county_of(M, b2)
            if c2 is None:
                warnings.append('holy site %s: barony %s is not on MPE\'s map' % (k, b2))
                continue
            for i, (kk, oo, x) in enumerate(v):
                if kk == 'barony':
                    v[i] = (kk, oo, b2)
                elif kk == 'county':
                    v[i] = (kk, oo, c2)
        elif c and c not in M:
            warnings.append('holy site %s: county %s is not on MPE\'s map' % (k, c))
    return HEADER % src + '\n' + P.write(items)


